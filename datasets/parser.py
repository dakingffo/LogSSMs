from __future__ import annotations

import json
import random
from bisect import bisect_right
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Literal


DatasetRole = Literal["system", "user", "assistant", "tool"]
RecordParser = Callable[[dict[str, Any]], "DatasetRecord"]


@dataclass(frozen=True)
class DatasetMessage:
    role        : DatasetRole
    content     : str
    tool_calls  : tuple[dict[str, Any], ...] | None = None
    tool_call_id: str | None = None


@dataclass(frozen=True)
class DatasetRecord:
    uid     : str
    category: str | None
    messages: tuple[DatasetMessage, ...]
    metadata: dict[str, Any] = field(default_factory=dict)

    @property
    def prompt(self) -> str:
        turns = self.user_turns
        if turns:
            return turns[0].content
        raise ValueError(f"Dataset record {self.uid!r} has no user message")

    @property
    def user_turns(self) -> tuple[DatasetMessage, ...]:
        """User inputs in conversation order.

        Recorded assistant messages are intentionally excluded. A serving benchmark
        must append the text generated by the server itself; replaying the recorded
        answer would break the token-prefix relationship with the preceding request.
        """
        return tuple(message for message in self.messages if message.role == "user")

    @property
    def num_turns(self) -> int:
        return len(self.user_turns)

    @property
    def initial_messages(self) -> tuple[DatasetMessage, ...]:
        """Messages before the first user input, normally a system prompt."""
        result = []
        for message in self.messages:
            if message.role == "user":
                break
            result.append(message)
        return tuple(result)


_DATASET_ROOT = Path(__file__).resolve().parent
_ALIASES = {
    "specbench"       : "spec_bench",
    "spec_bench"      : "spec_bench",
    "swebench"        : "swe_bench",
    "swe_bench"       : "swe_bench",
    "swe_agent"       : "swe_agent",
    "sweagent"        : "swe_agent",
    "sharegpt"        : "sharegpt",
    "lmsys"           : "lmsys_chat_1m",
    "lmsys_chat"      : "lmsys_chat_1m",
    "lmsys_chat_1m"   : "lmsys_chat_1m",
    "agentic_coding"  : "agentic_coding_trajectories",
    "agentic_coding_trajectories": "agentic_coding_trajectories",
}


def _normalize_name(name: str) -> str:
    return name.lower().replace("-", "_")


def _dataset_name(dataset: str | Path) -> str:
    path = Path(dataset)
    candidate = path.name if path.exists() and path.is_dir() else path.stem
    normalized = _normalize_name(candidate)
    if normalized in _ALIASES:
        return _ALIASES[normalized]

    for part in reversed(path.parts):
        normalized = _normalize_name(part)
        if normalized in _ALIASES:
            return _ALIASES[normalized]
    if path.is_file() and path.suffix in (".json", ".jsonl"):
        return "custom"
    raise ValueError(f"Cannot determine dataset type from {str(dataset)!r}")


def resolve_dataset_path(dataset: str | Path) -> Path:
    path = Path(dataset).expanduser()
    if path.exists():
        return path.resolve()

    normalized = _normalize_name(str(dataset))
    name = _ALIASES.get(normalized, normalized)
    path = _DATASET_ROOT / name
    if path.exists():
        return path

    raise FileNotFoundError(
        f"Dataset {str(dataset)!r} was not found as a path or under {_DATASET_ROOT}"
    )


def _message(
    role        : str,
    content     : Any,
    tool_calls  : Any = None,
    tool_call_id: Any = None,
) -> DatasetMessage | None:
    role = {
        "human": "user",
        "gpt"  : "assistant",
    }.get(role.lower(), role.lower())
    if role not in ("system", "user", "assistant", "tool"):
        return None
    if isinstance(tool_calls, str):
        tool_calls = json.loads(tool_calls)
    normalized_calls = None
    if tool_calls:
        calls = []
        for tool_call in tool_calls:
            tool_call = dict(tool_call)
            function = tool_call.get("function")
            if isinstance(function, dict) and isinstance(function.get("arguments"), str):
                function = dict(function)
                try:
                    function["arguments"] = json.loads(function["arguments"])
                except json.JSONDecodeError:
                    function["arguments"] = {"value": function["arguments"]}
                tool_call["function"] = function
            calls.append(tool_call)
        normalized_calls = tuple(calls)
    content = "" if content is None else str(content).strip()
    if not content and normalized_calls is None:
        return None
    return DatasetMessage(
        role=role,  # type: ignore[arg-type]
        content=content,
        tool_calls=normalized_calls,
        tool_call_id=str(tool_call_id) if tool_call_id else None,
    )


def _parse_spec_bench(record: dict[str, Any]) -> DatasetRecord:
    messages = tuple(
        DatasetMessage(role="user", content=str(turn))
        for turn in record["turns"]
        if str(turn).strip()
    )
    return DatasetRecord(
        uid=str(record["question_id"]),
        category=record.get("category"),
        messages=messages,
    )


def _parse_sharegpt(record: dict[str, Any]) -> DatasetRecord:
    messages = tuple(
        message
        for turn in record.get("conversations", ())
        if (message := _message(
            str(turn.get("from", turn.get("role", ""))),
            turn.get("value", turn.get("content", "")),
        )) is not None
    )
    return DatasetRecord(
        uid=str(record.get("id", "")),
        category="sharegpt",
        messages=messages,
    )


def _parse_swe_bench(record: dict[str, Any]) -> DatasetRecord:
    return DatasetRecord(
        uid=str(record["instance_id"]),
        category=str(record.get("repo", "swe_bench")),
        messages=(
            DatasetMessage(role="user", content=str(record["problem_statement"])),
        ),
    )


def _parse_lmsys(record: dict[str, Any]) -> DatasetRecord:
    messages = tuple(
        message
        for turn in record.get("conversation", ())
        if (message := _message(
            str(turn.get("role", turn.get("from", ""))),
            turn.get("content", turn.get("value", "")),
        )) is not None
    )
    return DatasetRecord(
        uid=str(record.get("conversation_id", "")),
        category=record.get("language"),
        messages=messages,
    )


def _parse_swe_agent(record: dict[str, Any]) -> DatasetRecord:
    uid = str(record["_uid"])
    messages = tuple(
        message
        for turn in record.get("history", ())
        if (message := _message(
            str(turn.get("role", "")),
            turn.get("content", ""),
        )) is not None
    )
    return DatasetRecord(
        uid=uid,
        category=uid.rsplit("-", 1)[0].replace("__", "/"),
        messages=messages,
    )


def _parse_agentic_coding(record: dict[str, Any]) -> DatasetRecord:
    raw_messages = json.loads(record["messages_json"])
    messages = tuple(
        message
        for turn in raw_messages
        if (message := _message(
            str(turn.get("role", "")),
            turn.get("content", ""),
            turn.get("tool_calls_json", turn.get("tool_calls")),
            turn.get("tool_call_id"),
        )) is not None
    )
    return DatasetRecord(
        uid=str(record["session_id"]),
        category=str(record["source_dataset"]),
        messages=messages,
        metadata={
            "source_id"      : record["source_id"],
            "agent_framework": record["agent_framework"],
            "recorded_model" : record["recorded_model"],
            "n_turns"        : record["n_turns"],
            "max_isl"        : record["max_isl"],
            "total_tokens"   : record["total_tokens"],
        },
    )


def _parse_custom(record: dict[str, Any]) -> DatasetRecord:
    if "turns" in record:
        messages = tuple(
            DatasetMessage(role="user", content=str(turn))
            for turn in record["turns"]
            if str(turn).strip()
        )
    elif "conversations" in record:
        return _parse_sharegpt(record)
    else:
        content = next(
            (
                record[key]
                for key in ("prompt", "question", "text", "instruction")
                if record.get(key)
            ),
            None,
        )
        if content is None:
            raise ValueError(f"Cannot find a prompt in dataset record: {record!r}")
        messages = (DatasetMessage(role="user", content=str(content)),)
    return DatasetRecord(
        uid=str(record.get("id", record.get("question_id", ""))),
        category=record.get("category"),
        messages=messages,
    )


def _iter_jsonl(path: Path) -> Iterator[dict[str, Any]]:
    with path.open(encoding="utf-8") as file:
        for line in file:
            if line.strip():
                yield json.loads(line)


def _iter_json(path: Path) -> Iterator[dict[str, Any]]:
    try:
        import ijson
    except ImportError as exc:
        raise RuntimeError(
            "Streaming JSON datasets requires ijson. Install the benchmark extras."
        ) from exc

    with path.open("rb") as file:
        yield from ijson.items(file, "item")


def _iter_swe_agent(path: Path) -> Iterator[dict[str, Any]]:
    paths = sorted(path.glob("trajs/*.traj")) if path.is_dir() else [path]
    if not paths:
        raise FileNotFoundError(f"No SWE-agent trajectories found under {path}")
    for trajectory_path in paths:
        with trajectory_path.open(encoding="utf-8") as file:
            record = json.load(file)
        record["_uid"] = trajectory_path.stem
        yield record


def _iter_parquet(paths: list[Path]) -> Iterator[dict[str, Any]]:
    try:
        import pyarrow.parquet as parquet
    except ImportError as exc:
        raise RuntimeError(
            "Parquet datasets require pyarrow. Install the benchmark extras."
        ) from exc

    for path in paths:
        parquet_file = parquet.ParquetFile(path)
        for batch in parquet_file.iter_batches(batch_size=256):
            yield from batch.to_pylist()


def _parquet_source(
    path: Path,
    name: str,
) -> tuple[list[Path], RecordParser]:
    if not path.is_dir():
        paths = [path]
    elif name == "swe_bench":
        paths = sorted(path.rglob("test-*.parquet"))
    else:
        paths = sorted(path.rglob("*.parquet"))
    if not paths:
        raise FileNotFoundError(f"No parquet files found under {path}")
    parser = {
        "swe_bench"                  : _parse_swe_bench,
        "agentic_coding_trajectories": _parse_agentic_coding,
    }.get(name, _parse_lmsys)
    return paths, parser


def _dataset_source(
    dataset: str | Path,
) -> tuple[Iterator[dict[str, Any]], RecordParser]:
    path = resolve_dataset_path(dataset)
    name = _dataset_name(path)

    if name == "spec_bench":
        source = path / "question.jsonl" if path.is_dir() else path
        return _iter_jsonl(source), _parse_spec_bench
    elif name == "sharegpt":
        source = (
            path / "ShareGPT_V3_unfiltered_cleaned_split.json"
            if path.is_dir() else path
        )
        return _iter_json(source), _parse_sharegpt
    elif name == "swe_agent":
        return _iter_swe_agent(path), _parse_swe_agent
    elif name in (
        "swe_bench",
        "lmsys_chat_1m",
        "agentic_coding_trajectories",
    ):
        paths, parser = _parquet_source(path, name)
        return _iter_parquet(paths), parser
    elif name == "custom":
        records = _iter_jsonl(path) if path.suffix == ".jsonl" else _iter_json(path)
        return records, _parse_custom
    else:
        raise ValueError(f"Unsupported dataset: {name}")


def iter_dataset(dataset: str | Path) -> Iterator[DatasetRecord]:
    records, parser = _dataset_source(dataset)
    for raw_record in records:
        record = parser(raw_record)
        if record.messages:
            yield record


def _sample_parquet(
    path      : Path,
    name      : str,
    count     : int,
    seed      : int,
    min_turns : int = 1,
    categories: set[str] | None = None,
) -> list[DatasetRecord]:
    try:
        import pyarrow.parquet as parquet
    except ImportError as exc:
        raise RuntimeError(
            "Parquet datasets require pyarrow. Install the benchmark extras."
        ) from exc

    paths, parser = _parquet_source(path, name)
    locations: list[tuple[Path, int, int, int]] = []
    ends: list[int] = []
    total = 0
    for parquet_path in paths:
        metadata = parquet.ParquetFile(parquet_path).metadata
        for row_group in range(metadata.num_row_groups):
            begin = total
            total += metadata.row_group(row_group).num_rows
            locations.append((parquet_path, row_group, begin, total))
            ends.append(total)

    if total < count:
        raise ValueError(
            f"Requested {count} records, but dataset only contains {total}; "
            "refusing to repeat prompts"
        )

    def read_rows(row_indices: list[int]) -> list[DatasetRecord]:
        grouped: dict[tuple[Path, int], list[tuple[int, int]]] = {}
        for output_idx, row_idx in enumerate(row_indices):
            location_idx = bisect_right(ends, row_idx)
            parquet_path, row_group, begin, _ = locations[location_idx]
            grouped.setdefault((parquet_path, row_group), []).append(
                (output_idx, row_idx - begin)
            )

        selected: list[DatasetRecord | None] = [None] * len(row_indices)
        for (parquet_path, row_group), rows in grouped.items():
            table = parquet.ParquetFile(parquet_path).read_row_group(row_group)
            for output_idx, row_idx in rows:
                selected[output_idx] = parser(table.slice(row_idx, 1).to_pylist()[0])
        return [record for record in selected if record is not None]

    generator = random.Random(seed)
    if min_turns == 1 and categories is None:
        result = [
            record for record in read_rows(generator.sample(range(total), count))
            if record.messages
        ]
        if len(result) != count:
            raise ValueError("Sampled parquet records contain empty conversations")
        return result

    # Multi-turn records are common in LMSYS but not guaranteed. Draw an expanding,
    # deterministic random candidate set so a small benchmark does not scan a million
    # parquet rows merely to filter by turn count.
    candidate_count = min(total, max(64, count * 4))
    while True:
        candidates = read_rows(generator.sample(range(total), candidate_count))
        result = [
            record for record in candidates
            if record.messages
            and record.num_turns >= min_turns
            and (categories is None or record.category in categories)
        ]
        if len(result) >= count:
            return result[:count]
        if candidate_count == total:
            break
        candidate_count = min(total, candidate_count * 2)

    raise ValueError(
        f"Requested {count} records with at least {min_turns} user turns, "
        f"but only found {len(result)}; refusing to repeat conversations"
    )


def _category_set(categories: str | None) -> set[str] | None:
    if categories is None:
        return None
    return {category.strip() for category in categories.split(",") if category.strip()}


def load_dataset(
    dataset   : str | Path,
    categories: str | None = None,
) -> list[DatasetRecord]:
    selected = _category_set(categories)
    return [
        record
        for record in iter_dataset(dataset)
        if selected is None or record.category in selected
    ]


def sample_dataset(
    dataset   : str | Path,
    count     : int,
    seed      : int,
    categories: str | None = None,
    min_turns : int = 1,
) -> list[DatasetRecord]:
    if count < 0:
        raise ValueError(f"count must be non-negative, got {count}")
    if min_turns < 1:
        raise ValueError(f"min_turns must be positive, got {min_turns}")

    selected_categories = _category_set(categories)
    path = resolve_dataset_path(dataset)
    name = _dataset_name(path)
    if name in (
        "swe_bench",
        "lmsys_chat_1m",
        "agentic_coding_trajectories",
    ):
        return _sample_parquet(
            path,
            name,
            count,
            seed,
            min_turns=min_turns,
            categories=selected_categories,
        )

    generator = random.Random(seed)
    reservoir: list[DatasetRecord] = []
    seen = 0
    for record in iter_dataset(dataset):
        if (
            selected_categories is not None
            and record.category not in selected_categories
        ):
            continue
        if record.num_turns < min_turns:
            continue
        seen += 1
        if len(reservoir) < count:
            reservoir.append(record)
        else:
            replace = generator.randrange(seen)
            if replace < count:
                reservoir[replace] = record

    if seen < count:
        if min_turns == 1:
            raise ValueError(
                f"Requested {count} records, but dataset selection only contains "
                f"{seen}; refusing to repeat prompts"
            )
        raise ValueError(
            f"Requested {count} records with at least {min_turns} user turns, "
            f"but dataset selection only contains {seen}; refusing to repeat "
            "conversations"
        )
    generator.shuffle(reservoir)
    return reservoir
